import React, { useState } from 'react';
import { Navbar, ViewType } from './components/Navbar';
import { ProblemDirectory } from './components/ProblemDirectory';
import { SandboxStudio } from './components/SandboxStudio';
import { TechnicalQuestionsView } from './components/TechnicalQuestionsView';
import { BehavioralQuestionsView } from './components/BehavioralQuestionsView';
import { LoginPage, UserProfile } from './components/LoginPage';
import { AiProblemGeneratorModal } from './components/AiProblemGeneratorModal';
import { MOCK_PROBLEMS } from './data/mockProblems';
import { Problem } from './types';
import { CheckCircle2, X } from 'lucide-react';

export function App() {
  const [problems, setProblems] = useState<Problem[]>(MOCK_PROBLEMS);
  const [activeProblem, setActiveProblem] = useState<Problem>(MOCK_PROBLEMS[0]);
  const [currentView, setCurrentView] = useState<ViewType>('directory');
  const [previousView, setPreviousView] = useState<ViewType>('directory');
  
  // User Authentication State
  const [currentUser, setCurrentUser] = useState<UserProfile | null>(null);
  const [toastMessage, setToastMessage] = useState<string | null>(null);

  // Modals
  const [isGeneratorOpen, setIsGeneratorOpen] = useState(false);

  // Handle View Changes with history tracking
  const navigateTo = (view: ViewType) => {
    if (view === 'login' && currentView !== 'login') {
      setPreviousView(currentView);
    }
    setCurrentView(view);
  };

  // When a user selects a problem from catalog
  const handleSelectProblem = (problem: Problem) => {
    setActiveProblem(problem);
    setCurrentView('sandbox');
  };

  // When custom problem is generated by AI
  const handleProblemGenerated = (newProblem: Problem) => {
    setProblems(prev => [newProblem, ...prev]);
    setActiveProblem(newProblem);
    setCurrentView('sandbox');
  };

  // Auth Handlers
  const handleLoginSuccess = (user: UserProfile) => {
    setCurrentUser(user);
    setToastMessage(`Signed in as ${user.name} via ${user.provider.toUpperCase()}`);
    // Return to previous view or directory
    setCurrentView(previousView === 'login' ? 'directory' : previousView);
    setTimeout(() => setToastMessage(null), 4000);
  };

  const handleLogout = () => {
    setCurrentUser(null);
    setToastMessage('Successfully logged out.');
    setTimeout(() => setToastMessage(null), 3000);
  };

  return (
    <div className="min-h-screen bg-[#fafafa] text-slate-900 flex flex-col font-sans selection:bg-indigo-100 selection:text-indigo-900">
      
      {/* Toast Notification Banner */}
      {toastMessage && (
        <div className="fixed bottom-6 right-6 z-50 flex items-center space-x-2.5 px-4 py-3 bg-slate-950 text-white text-xs font-semibold rounded-xl shadow-2xl border border-slate-800 animate-in fade-in slide-in-from-bottom-2 duration-200">
          <CheckCircle2 className="w-4 h-4 text-emerald-400" />
          <span>{toastMessage}</span>
          <button 
            onClick={() => setToastMessage(null)}
            className="ml-2 text-slate-400 hover:text-white"
          >
            <X className="w-3.5 h-3.5" />
          </button>
        </div>
      )}

      {/* Top Global Navigation Bar */}
      <Navbar
        currentView={currentView}
        setCurrentView={navigateTo}
        onOpenGenerator={() => setIsGeneratorOpen(true)}
        activeProblemTitle={activeProblem.title}
        user={currentUser}
        onLogout={handleLogout}
      />

      {/* Main Content Router */}
      <main className="flex-1 flex flex-col">
        {currentView === 'directory' && (
          <ProblemDirectory
            problems={problems}
            onSelectProblem={handleSelectProblem}
            onOpenGenerator={() => setIsGeneratorOpen(true)}
          />
        )}

        {currentView === 'sandbox' && (
          <SandboxStudio
            problem={activeProblem}
            onProceedToTechnicalQuestions={() => setCurrentView('technical-questions')}
            onBackToCatalog={() => setCurrentView('directory')}
          />
        )}

        {currentView === 'technical-questions' && (
          <TechnicalQuestionsView
            problem={activeProblem}
            onBackToSandbox={() => setCurrentView('sandbox')}
          />
        )}

        {currentView === 'behavioral-questions' && (
          <BehavioralQuestionsView />
        )}

        {currentView === 'login' && (
          <LoginPage
            onLoginSuccess={handleLoginSuccess}
            onCancel={() => setCurrentView(previousView === 'login' ? 'directory' : previousView)}
          />
        )}
      </main>

      {/* AI Problem Generator Modal */}
      <AiProblemGeneratorModal
        isOpen={isGeneratorOpen}
        onClose={() => setIsGeneratorOpen(false)}
        onProblemGenerated={handleProblemGenerated}
      />

    </div>
  );
}

export default App;
